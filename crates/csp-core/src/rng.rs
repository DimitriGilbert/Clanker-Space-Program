    /// The preimage is assembled byte-by-byte straight from the §2.7 spec —
    /// `KDF_VERSION(u8) || save_seed(u64) || tag(u16) || entity(u64) ||
    /// counter(u64)` — so this test pins the *construction* (plain BLAKE3,
    /// field widths, order), not just the outputs.
    #[test]
    fn kdf_preimage_layout_is_the_literal_spec() {
        let save_seed = 42u64;
        let key = StreamKey {
            tag: StreamTag::Ignition,
            entity: 7,
            counter: 3,
        };
        let mut preimage = Vec::with_capacity(27);
        preimage.extend(1u8.to_le_bytes()); // KDF_VERSION = 1
        preimage.extend(save_seed.to_le_bytes());
        preimage.extend(1u16.to_le_bytes()); // StreamTag::Ignition discriminant
        preimage.extend(7u64.to_le_bytes()); // entity
        preimage.extend(3u64.to_le_bytes()); // counter
        assert_eq!(preimage.len(), 27);
        assert_eq!(
            derive_key(save_seed, key),
            *blake3::hash(&preimage).as_bytes()
        );
    }

