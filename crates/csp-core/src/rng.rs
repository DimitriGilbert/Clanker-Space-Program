//! Deterministic RNG streams (PLAN §2.7). No global RNG exists.
//!
//! The scheme *reseeds per key* — it does not advance a shared stream
//! position. "Counters are part of the save" means a stored index replays the
//! exact draw, so reloading a save and re-flying cannot reroll a drawn value
//! (anti-save-scum by construction, and required for replay).

use rand_chacha::ChaCha8Rng;
use rand_core::{Rng, SeedableRng};

use crate::StableDiscriminant;

/// Version of the key-derivation scheme (PLAN §2.7) — the single version
/// source. It is the first byte of every KDF preimage and is recorded in the
/// save header so stale saves are detected. Bump it in the same commit that
/// changes the preimage layout, and say why in the message.
pub const KDF_VERSION: u8 = 1;

/// Named deterministic RNG streams (PLAN §2.7).
///
/// **APPEND-ONLY:** the explicit `u16` discriminants are part of the KDF
/// preimage (and are the §7.1 rule-7 enum encoding). Never reorder or
/// renumber variants — doing so silently rewrites every pre-drawn value in
/// every existing save. New variants go at the end with the next free
/// discriminant and require a `KDF_VERSION` bump.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[repr(u16)]
pub enum StreamTag {
    Reliability = 0,
    Ignition = 1,
    Contracts = 2,
    Generation = 3,
}

impl StreamTag {
    /// The stable `u16` discriminant — the only representation of this enum
    /// that may enter the KDF preimage or the §7.1 canonical stream.
    pub const fn discriminant(self) -> u16 {
        self as u16
    }
}

/// Rule-7 hashing writes the enum's declared `#[repr(u16)]` discriminant —
/// the same value the KDF preimage uses.
impl StableDiscriminant for StreamTag {
    fn discriminant(&self) -> u16 {
        StreamTag::discriminant(*self)
    }
}

/// Full key for one deterministic draw (PLAN §2.7). `counter` indexes into
/// the stream — reseeding per counter, never advancing shared stream
/// position, so a stored counter replays the exact draw.
#[derive(Clone, Copy, Debug)]
pub struct StreamKey {
    pub tag: StreamTag,
    pub entity: u64,
    pub counter: u64,
}

/// The §2.7 KDF: the full 32-byte ChaCha key is plain BLAKE3 over the
/// little-endian concatenation
/// `KDF_VERSION_LE || save_seed_LE || tag_LE || entity_LE || counter_LE`
/// with fixed field widths `u8 | u64 | u16 | u64 | u64` — a 27-byte preimage
/// hashed with a plain `blake3::Hasher` (not derive-key mode; `KDF_VERSION`
/// is the only version input).
///
/// Field-width note: the plan writes `tag_LE` without a width; `tag` is
/// encoded as [`StreamTag`]'s explicit `u16` discriminant, the only stable
/// representation §7.1 rule 7 assigns to enums.
///
/// Never `SeedableRng::seed_from_u64`: its output is a `rand_core`
/// implementation detail, and a dependency bump would silently change every
/// pre-drawn reliability threshold in every existing save.
pub fn derive_key(save_seed: u64, key: StreamKey) -> [u8; 32] {
    let mut h = blake3::Hasher::new();
    h.update(&KDF_VERSION.to_le_bytes());
    h.update(&save_seed.to_le_bytes());
    h.update(&key.tag.discriminant().to_le_bytes());
    h.update(&key.entity.to_le_bytes());
    h.update(&key.counter.to_le_bytes());
    *h.finalize().as_bytes()
}

/// A deterministic ChaCha8 stream for one `StreamKey` (§2.7's `rng`).
pub fn stream(save_seed: u64, key: StreamKey) -> ChaCha8Rng {
    ChaCha8Rng::from_seed(derive_key(save_seed, key))
}

/// Convenience: draw a uniform `f64` in `[0, 1)` from a derived stream —
/// the top 53 bits of the first `u64` scaled by 2⁻⁵³, the same fixed-width
/// draw on every platform.
pub fn uniform(save_seed: u64, key: StreamKey) -> f64 {
    let mut rng = stream(save_seed, key);
    uniform01(&mut rng)
}

/// The `[0, 1)` draw applied to a stream position — top 53 bits of the
/// next `u64` scaled by 2⁻⁵³. [`uniform`] is this applied to the first
/// position of a key-derived stream; consumers that need several draws
/// from one seeded stream (a fixed draw order, not per-key reseeding)
/// call this directly so the determinism-critical constants (shift 11,
/// 53-bit precision, 2⁻⁵³ scale) exist exactly once.
pub fn uniform01(rng: &mut impl Rng) -> f64 {
    (rng.next_u64() >> 11) as f64 * (1.0 / (1u64 << 53) as f64)
}

